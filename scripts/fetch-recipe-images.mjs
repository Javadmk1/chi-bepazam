import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const recipesSource = await fs.readFile(path.join(root, "src/data/recipes.ts"), "utf8");
const recipes = [...recipesSource.matchAll(/id:\s*"([^"]+)"\s*,\s*title:\s*"([^"]+)"/g)]
  .map(match => ({ id: match[1], title: match[2] }));
const outputDir = path.join(root, "assets/recipes");
await fs.mkdir(outputDir, { recursive: true });

const allowedLicense = value => {
  const license = String(value ?? "").toLowerCase();
  if (/\\bNC\\b|\\bND\\b/.test(license) || license.includes("noncommercial") || license.includes("no derivatives")) return false;
  return license.includes("cc0") || license.includes("public domain") ||
    license.includes("cc by") || license.includes("cc-by");
};
const clean = value => String(value ?? "").replace(/<[^>]*>/g, " ").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const entries = [];
const attribution = [];
const usedFileTitles = new Set();

for (const recipe of recipes) {
  const terms = recipe.id.replace(/-/g, " ");
  const query = `filetype:bitmap "${terms}" OR "${recipe.title}" food`;
  try {
    const params = new URLSearchParams({
      action: "query", generator: "search", gsrsearch: query,
      gsrnamespace: "6", gsrwhat: "text", gsrlimit: "10",
      prop: "imageinfo", iiprop: "url|extmetadata", iiurlwidth: "640",
      format: "json", origin: "*"
    });
    const response = await fetch(`https://commons.wikimedia.org/w/api.php?${params}`, {
      headers: { "User-Agent": "ChiBepazam/1.0 (recipe photo catalog; open-source app)" }
    });
    if (!response.ok) throw new Error(`Commons search HTTP ${response.status}`);
    const data = await response.json();
    const pages = Object.values(data.query?.pages ?? {}).sort((a, b) => (a.index ?? 999) - (b.index ?? 999));
    let chosen;
    for (const page of pages) {
      const info = page.imageinfo?.[0];
      const meta = info?.extmetadata ?? {};
      if (!info?.thumburl || usedFileTitles.has(page.title) || !allowedLicense(meta.LicenseShortName?.value)) continue;
      chosen = { page, info, meta };
      break;
    }
    if (!chosen) {
      entries.push({ id: recipe.id, title: recipe.title, status: "not-found" });
      await wait(120);
      continue;
    }

    usedFileTitles.add(chosen.page.title);
    const imageResponse = await fetch(chosen.info.thumburl, {
      headers: { "User-Agent": "ChiBepazam/1.0 (recipe photo catalog; open-source app)" }
    });
    if (!imageResponse.ok) throw new Error(`image HTTP ${imageResponse.status}`);
    const bytes = Buffer.from(await imageResponse.arrayBuffer());
    if (bytes.length < 3000 || bytes.length > 1200000) throw new Error("image size outside accepted range");
    const contentType = imageResponse.headers.get("content-type") ?? "";
    const extension = contentType.includes("png") ? "png" : contentType.includes("webp") ? "webp" : "jpg";
    const filename = `${recipe.id}.${extension}`;
    await fs.writeFile(path.join(outputDir, filename), bytes);

    entries.push({ id: recipe.id, title: recipe.title, filename, status: "downloaded" });
    attribution.push([
      recipe.title,
      clean(chosen.page.title),
      clean(chosen.meta.LicenseShortName?.value),
      clean(chosen.meta.Artist?.value),
      chosen.info.descriptionurl ?? chosen.info.url
    ].join(" | "));
  } catch (error) {
    entries.push({ id: recipe.id, title: recipe.title, status: "error", reason: String(error?.message ?? error) });
  }
  await wait(120);
}

const imports = entries.filter(item => item.status === "downloaded")
  .map(item => `  "${item.id}": require("../../assets/recipes/${item.filename}")`);
const mapSource = `// Generated by scripts/fetch-recipe-images.mjs during the Android build.\nexport const recipeImages: Record<string, number> = {\n${imports.join(",\n")}\n};\n`;
await fs.writeFile(path.join(root, "src/data/recipe-images.ts"), mapSource, "utf8");
await fs.writeFile(path.join(outputDir, "ATTRIBUTION.txt"),
  "Recipe photo attributions (Wikimedia Commons)\n\n" + attribution.join("\n") + "\n", "utf8");
await fs.writeFile(path.join(outputDir, "image-fetch-report.json"), JSON.stringify(entries, null, 2), "utf8");
const downloaded = entries.filter(item => item.status === "downloaded").length;
console.log(`Recipe photos downloaded: ${downloaded}/${recipes.length}. Missing: ${recipes.length - downloaded}. Attribution saved to assets/recipes/ATTRIBUTION.txt`);
